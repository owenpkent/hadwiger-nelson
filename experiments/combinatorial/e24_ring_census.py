FIELDS = {
    "Q (rational units)": (1, 1, rational_units),
    "Q(sqrt3) triangular": (3, 1, rot60),
    "Q(sqrt3,sqrt11) Moser": (3, 11, moser_units),
}


def describe(fld, units, radius, label, want_chi=None, cap=60000):
    t0 = time.time()
    pts, truncated = ball(fld, units, radius, cap=cap)
    g = udg(fld, pts)
    chi = chromatic_number(g) if g.number_of_edges() else 1
    dt = round(time.time() - t0, 1)
    ok = (want_chi is None or chi == want_chi)
    print(f"  [{'ok' if ok else 'MISMATCH'}] {label}: radius {radius}, "
          f"{len(pts)} points{' (CAPPED)' if truncated else ''}, "
          f"{g.number_of_edges()} edges, chi = {chi}"
          f"{'' if want_chi is None else f' (want {want_chi})'} [{dt}s]",
          flush=True)
    return {"label": label, "radius": radius, "points": len(pts),
            "capped": truncated, "edges": g.number_of_edges(), "chi": chi,
            "want_chi": want_chi, "ok": ok, "seconds": dt}


def calibrate():
    print("E24 calibration: the control first, then the known fields", flush=True)
    ok = True
    rows = []

    fq = Fld(1, 1)
    for r in (2, 3):
        row = describe(fq, unit_vectors(fq, rational_units(fq)), r,
                       "Q^2 control (Woodall: chi = 2)", want_chi=2)
        ok &= row["ok"]
        rows.append(row)

    f3 = Fld(3, 1)
    row = describe(f3, unit_vectors(f3, rot60(f3)), 3,
                   "triangular lattice (chi = 3)", want_chi=3)
    ok &= row["ok"]
    rows.append(row)

    fm = Fld(3, 11)
    row = describe(fm, unit_vectors(fm, moser_units(fm)), 2,
                   "Moser field Q(sqrt3,sqrt11) (spindle lives here: chi = 4)",
                   want_chi=4)
    ok &= row["ok"]
    rows.append(row)

    CACHE.mkdir(parents=True, exist_ok=True)
    (CACHE / "calibration.json").write_text(json.dumps(rows, indent=2))
    print(f"calibration: {'ALL PASS' if ok else 'FAILURE'}", flush=True)
    return ok


def sweep(radius, primes, cap=60000):
    """Fields Q(sqrt3, sqrt p): does any reach chi >= 5 inside a small ball?"""
    CACHE.mkdir(parents=True, exist_ok=True)
    out = []
    for p in primes:
        f = Fld(3, p)
        rotors = [u for den in range(2, 13) for u in sqrt_units(f, p, den)]
        if not rotors:
            print(f"  Q(sqrt3,sqrt{p}): no unit vector with sin = sqrt({p})/d "
                  f"for d <= 12, skipped", flush=True)
            continue
        base = rot60(f)
        for r in rotors:
            base = with_rotor(f, base, r)
        units = unit_vectors(f, base)
        row = describe(f, units, radius, f"Q(sqrt3,sqrt{p}) [{len(units)} units]",
                       cap=cap)
        row["p"] = p
        out.append(row)
        (CACHE / f"sweep_r{radius}.json").write_text(json.dumps(out, indent=2))
    best = [r for r in out if (r["chi"] or 0) >= 5]
    print(f"\nsweep: {len(out)} fields, {len(best)} reaching chi >= 5", flush=True)
    for r in best:
        print(f"  *** {r['label']}: chi = {r['chi']} at radius {radius} ***",
              flush=True)
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--calibrate", action="store_true")
    ap.add_argument("--field", type=str, help="a,b for Q(sqrt a, sqrt b)")
    ap.add_argument("--radius", type=int, default=2)
    ap.add_argument("--sweep", action="store_true")
    ap.add_argument("--cap", type=int, default=60000)
    ap.add_argument("--primes", type=str,
                    default="7,11,15,19,23,31,35,39,43,47,55,59")
    args = ap.parse_args()
    if args.calibrate:
        return 0 if calibrate() else 1
    if args.sweep:
        return sweep(args.radius, [int(x) for x in args.primes.split(",")],
                     cap=args.cap)
    if args.field:
        a, b = [int(x) for x in args.field.split(",")]
        f = Fld(a, b)
        base = rot60(f)
        for r in [u for den in range(2, 13) for u in sqrt_units(f, b, den)]:
            base = with_rotor(f, base, r)
        units = unit_vectors(f, base)
        describe(f, units, args.radius, f"Q(sqrt{a},sqrt{b})", cap=args.cap)
        return 0
    ap.print_help()
    return 1


