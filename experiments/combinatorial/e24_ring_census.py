# ------------------------------------------------- exact biquadratic elements

class Fld:
    """Elements of $\\mathbb{Q}(\\sqrt a, \\sqrt b)$ as 4-tuples of Fractions over
    the basis $(1, \\sqrt a, \\sqrt b, \\sqrt{ab})$. Squarefree a, b; a=b=1 gives
    plain $\\mathbb{Q}$ (the control), where only the first coordinate is used."""

    __slots__ = ("a", "b")

    def __init__(self, a, b):
        self.a, self.b = a, b

    def zero(self):
        return (Fraction(0),) * 4

    def one(self):
        return (Fraction(1), Fraction(0), Fraction(0), Fraction(0))

    def add(self, x, y):
        return tuple(p + q for p, q in zip(x, y))

    def sub(self, x, y):
        return tuple(p - q for p, q in zip(x, y))

    def mul(self, x, y):
        a, b = self.a, self.b
        x0, x1, x2, x3 = x
        y0, y1, y2, y3 = y
        # (x0 + x1 sa + x2 sb + x3 sab)(y0 + y1 sa + y2 sb + y3 sab)
        return (
            x0 * y0 + a * x1 * y1 + b * x2 * y2 + a * b * x3 * y3,
            x0 * y1 + x1 * y0 + b * (x2 * y3 + x3 * y2),
            x0 * y2 + x2 * y0 + a * (x1 * y3 + x3 * y1),
            x0 * y3 + x3 * y0 + x1 * y2 + x2 * y1,
        )

    def is_one(self, x):
        return x == self.one()

    def approx(self, x):
        ra, rb = math.sqrt(self.a), math.sqrt(self.b)
        return float(x[0]) + float(x[1]) * ra + float(x[2]) * rb + float(x[3]) * ra * rb


def q(*vals):
    return tuple(Fraction(v) for v in vals) + (Fraction(0),) * (4 - len(vals))


# ------------------------------------------------------------- vector systems

def unit_vectors(fld, spec):
    """Build a negation-closed set of unit vectors from a spec of (x, y) pairs,
    verifying x^2 + y^2 = 1 EXACTLY for each. A generator that fails this is a
    bug, not a rounding issue, so it raises."""
    out = []
    for (x, y) in spec:
        s = fld.add(fld.mul(x, x), fld.mul(y, y))
        if not fld.is_one(s):
            raise ValueError(f"not a unit vector: {x}, {y} has norm {s}")
        for v in ((x, y), (fld.sub(fld.zero(), x), fld.sub(fld.zero(), y))):
            if v not in out:
                out.append(v)
    return out


def rot60(fld):
    """Sixth roots of unity in Q(sqrt 3): (1,0) and (1/2, sqrt3/2)."""
    half = q(Fraction(1, 2))
    r3_2 = (Fraction(0), Fraction(1, 2), Fraction(0), Fraction(0))   # sqrt(3)/2
    return [(fld.one(), fld.zero()), (half, r3_2),
            (q(Fraction(-1, 2)), r3_2)]


def rotate(fld, v, rotor):
    """Complex multiplication: rotate v by the unit vector `rotor`."""
    (x, y), (c, s) = v, rotor
    return (fld.sub(fld.mul(x, c), fld.mul(y, s)),
            fld.add(fld.mul(x, s), fld.mul(y, c)))


def with_rotor(fld, base, rotor):
    """base, plus base rotated by rotor and by its inverse.

    Rotating the GENERATING SET is the point. A rotor applied only to $(1,0)$
    adds one vector and generates nothing new: the Moser spindle is a rhombus
    plus a ROTATED COPY of that rhombus, so every generator has to be rotated or
    the copy is unreachable. (The first version of this file rotated only
    $(1,0)$, and the calibration caught it: the Moser field came back
    $3$-chromatic.)
    """
    c, s = rotor
    inv = (c, fld.sub(fld.zero(), s))
    out = list(base)
    for r in (rotor, inv):
        for v in base:
            w = rotate(fld, v, r)
            if w not in out:
                out.append(w)
    return out


def with_rotor_powers(fld, base, rotor, k):
    """base closed under rotor^j for |j| <= k.

    A rotor of infinite order generates a new unit vector at every power, and the
    known chi=5 constructions use that: they are NOT one rotated copy of the
    hexagonal lattice but a tower of them. Applying the rotor once (`with_rotor`)
    is enough to bind the Moser spindle and NOT enough to reach chi=5, which the
    calibration showed directly: the radius-4 ball of the Moser field over 18
    vectors is 4-COLORABLE, even though de Grey's 1581-vertex chi=5 graph lives in
    that same field. Any ball containing that graph must be non-4-colorable, so an
    18-vector ball simply does not contain it.
    """
    out = list(base)
    cur_f, cur_b = rotor, (rotor[0], fld.sub(fld.zero(), rotor[1]))
    for _ in range(k):
        for r in (cur_f, cur_b):
            for v in base:
                w = rotate(fld, v, r)
                if w not in out:
                    out.append(w)
        cur_f = rotate(fld, cur_f, rotor)
        cur_b = rotate(fld, cur_b, (rotor[0], fld.sub(fld.zero(), rotor[1])))
    return out


def moser_rotor(fld):
    """The Moser rotation: cos t = 5/6, sin t = sqrt(11)/6, needs sqrt 11."""
    return (q(Fraction(5, 6)),
            (Fraction(0), Fraction(0), Fraction(1, 6), Fraction(0)))


def moser_units(fld):
    return with_rotor(fld, rot60(fld), moser_rotor(fld))


def rational_units(fld):
    """Pythagorean unit vectors. The Q^2 control: every point stays rational."""
    return [(q(1), q(0)), (q(Fraction(3, 5)), q(Fraction(4, 5))),
            (q(Fraction(5, 13)), q(Fraction(12, 13))),
            (q(Fraction(8, 17)), q(Fraction(15, 17)))]


def sqrt_units(fld, p, den):
    """A unit vector with cos = c/den and sin = sqrt(p)/den, when c^2 + p = den^2."""
    c2 = den * den - p
    if c2 < 0:                       # den^2 < p: no such unit vector
        return []
    c = math.isqrt(c2)
    if c * c != c2:
        return []
    return [(q(Fraction(c, den)), (Fraction(0), Fraction(0), Fraction(1, den),
                                   Fraction(0)))]


# --------------------------------------------------------------- ball + graph

def ball(fld, units, radius, cap=200000):
    """All points reachable from the origin in <= radius unit steps, exactly."""
    origin = (fld.zero(), fld.zero())
    seen = {origin}
    frontier = [origin]
    for _ in range(radius):
        nxt = []
        for (px, py) in frontier:
            for (ux, uy) in units:
                pt = (fld.add(px, ux), fld.add(py, uy))
                if pt not in seen:
                    seen.add(pt)
                    nxt.append(pt)
                    if len(seen) > cap:
                        return sorted(seen), True
        frontier = nxt
    return sorted(seen), False


def udg(fld, pts):
    """The unit-distance graph on pts, by exact distance-squared == 1.

    Buckets on a float key first so the exact test runs only on plausible pairs;
    the bucket is a filter, never the decision.
    """
    g = nx.Graph()
    g.add_nodes_from(range(len(pts)))
    approx = [(fld.approx(x), fld.approx(y)) for (x, y) in pts]
    grid = {}
    for i, (ax, ay) in enumerate(approx):
        grid.setdefault((math.floor(ax), math.floor(ay)), []).append(i)
    for i, (ax, ay) in enumerate(approx):
        cx, cy = math.floor(ax), math.floor(ay)
        for dx in (-2, -1, 0, 1, 2):
            for dy in (-2, -1, 0, 1, 2):
                for j in grid.get((cx + dx, cy + dy), ()):
                    if j <= i:
                        continue
                    bx, by = approx[j]
                    d2 = (ax - bx) ** 2 + (ay - by) ** 2
                    if abs(d2 - 1.0) > 1e-6:
                        continue
                    dxv = fld.sub(pts[i][0], pts[j][0])
                    dyv = fld.sub(pts[i][1], pts[j][1])
                    s = fld.add(fld.mul(dxv, dxv), fld.mul(dyv, dyv))
                    if fld.is_one(s):
                        g.add_edge(i, j)
    return g


def chi_at_least(g, k, timeout=None):
    """Is chi(G) >= k? Asks the repo portfolio for a (k-1)-coloring."""
    if g.number_of_edges() == 0:
        return False
    nodes = list(g.nodes())
    idx = {v: i for i, v in enumerate(nodes)}
    edges = [(idx[u], idx[v]) for u, v in g.edges()]
    res = solve_color(len(nodes), edges, k - 1, symbreak=True)["result"]
    return not res


def chromatic_number(g, hi=7):
    """Exact chi by SAT, walking up from 2. Cores only, so it stays cheap."""
    core = g.subgraph(max(nx.connected_components(g), key=len)) if \
        g.number_of_edges() else g
    for k in range(2, hi + 1):
        nodes = list(core.nodes())
        idx = {v: i for i, v in enumerate(nodes)}
        edges = [(idx[u], idx[v]) for u, v in core.edges()]
        if solve_color(len(nodes), edges, k, symbreak=True)["result"]:
            return k
    return None


