r"""E24: which RINGS support a $\chi = 5$ unit-distance graph?

The lemma_db frontier's top item is a $\chi = 5$ UDG outside the P510 lineage
(route ii of L55: one carrying a wide imprimitive interface). L57 proved the
whole known lineage forcing-sterile by construction, so the missing object cannot
be filed out of what we have; it needs a different construction principle. This
module attacks the most concrete version of "different": a different NUMBER
FIELD.

Every graph in the lineage lives in one place. Unit vectors at angle $\theta$ with
$\cos\theta \in \mathbb{Q}(\sqrt3,\sqrt{11})$ generate the Moser spindle, the
Golomb graph, P510 and de Grey 1585 alike; the field is not incidental, it is
where the rigidity that forces $\chi \ge 5$ lives. The question here is whether
any OTHER small field does the same job, and the experiment is a census: fix a
generating set of unit vectors, grow the ball of points reachable in $\le k$ unit
steps, build the unit-distance graph on it exactly, and ask a SAT solver for its
chromatic number.

WHY THIS IS NOT A NAIVE REPEAT OF E1D. L11 recorded a negative for an
orbit-search over alternate rings: rotations did not auto-bind copies of a seed.
That searched for ORBITS of a fixed seed graph under rotations. This searches the
FULL BALL of the vector system, which is the object de Grey actually used (his
graph is a subgraph of a 4-step ball), and it asks for $\chi$ of the whole ball
rather than of a hand-assembled union.

THE CONTROL IS THE POINT. The wrong-approach detector applies with full force
here: on $\mathbb{Q}^2$ the unit-distance graph has $\chi = 2$ (Woodall 1973), so
any ring whose unit vectors have rational coordinates MUST come back
$2$-colorable. A method that reports $\chi \ge 3$ for a rational vector system is
broken, and the ladder below runs that case first, before any positive claim is
made about any other field.

SCOPE, MEASURED: THIS MODULE IS CALIBRATED AT $\chi \le 4$ ONLY. The rung that
would license a $\chi \ge 5$ negative is the Moser field itself, where de Grey's
$1581$-vertex $\chi = 5$ graph provably lives; since that graph is connected with
unit edges, some ball of that field must be non-$4$-colorable. Every ball this
module can build there is $4$-colorable, including $11{,}593$ points at rotor
power $3$ and radius $3$. So the generated vector system does not contain it, and
"no field reached $\chi \ge 5$" is a statement about the generator set, NOT about
the fields. Positive findings ($\chi = 4$ in two fields, the 56-vertex critical
core) are verified directly and stand.

CALIBRATION LADDER (`--calibrate`):
  (1) $\mathbb{Q}^2$, generated by the rational unit vectors $(1,0)$, $(3/5,4/5)$,
      $(5/13,12/13)$: must be exactly $2$-colorable at every radius. This is the
      structural firewall, not a smoke test.
  (2) the triangular lattice ($6$th roots of unity, $\mathbb{Q}(\sqrt3)$): must be
      $3$-chromatic, and must contain triangles.
  (3) the Moser field $\mathbb{Q}(\sqrt3,\sqrt{11})$: the $2$-step ball must
      already contain a $\chi = 4$ subgraph (the spindle lives there).

Arithmetic is exact throughout: points are integer coordinate vectors over the
basis $(1, \sqrt a, \sqrt b, \sqrt{ab})$ of a biquadratic field, with a shared
denominator, so "distance exactly $1$" is an integer identity and never a float
comparison.

Usage:
    python -m experiments.combinatorial.e24_ring_census --calibrate
    python -m experiments.combinatorial.e24_ring_census --field 3,11 --radius 3
    python -m experiments.combinatorial.e24_ring_census --sweep --radius 2
"""
